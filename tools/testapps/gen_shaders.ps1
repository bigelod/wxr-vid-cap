# Compiles the test-app shaders and writes shaders_generated.h.
#
# Run this only when shaders.hlsl, cube.vert, or cube.frag change; the generated header is committed
# so normal builds do not need fxc or glslangValidator.

$ErrorActionPreference = "Stop"
$root = $PSScriptRoot
$temp = Join-Path $env:TEMP "wxr_testapp_shaders"
New-Item -ItemType Directory -Force -Path $temp | Out-Null

$fxc = Get-ChildItem "C:\Program Files (x86)\Windows Kits\10\bin" -Recurse -Filter "fxc.exe" -ErrorAction SilentlyContinue |
    Where-Object { $_.FullName -match "\\x64\\" } |
    Sort-Object FullName -Descending |
    Select-Object -First 1
if (-not $fxc) {
    throw "fxc.exe not found"
}
$fxc = $fxc.FullName

$glslang = $null
if ($env:VULKAN_SDK) {
    $candidate = Join-Path $env:VULKAN_SDK "Bin\glslangValidator.exe"
    if (Test-Path $candidate) { $glslang = $candidate }
}
if (-not $glslang) {
    $found = Get-ChildItem "D:\VulkanSDK" -Recurse -Filter "glslangValidator.exe" -ErrorAction SilentlyContinue |
        Sort-Object FullName -Descending |
        Select-Object -First 1
    if ($found) { $glslang = $found.FullName }
}
if (-not $glslang) {
    throw "glslangValidator.exe not found"
}

$hlsl = Join-Path $root "shaders.hlsl"

& $fxc /nologo /T vs_5_0 /E VSMain /Fo (Join-Path $temp "cube_vs5.cso") $hlsl
& $fxc /nologo /T ps_5_0 /E PSMain /Fo (Join-Path $temp "cube_ps5.cso") $hlsl
& $fxc /nologo /T vs_4_0 /E VSMain /Fo (Join-Path $temp "cube_vs4.cso") $hlsl
& $fxc /nologo /T ps_4_0 /E PSMain /Fo (Join-Path $temp "cube_ps4.cso") $hlsl

& $glslang -V -o (Join-Path $temp "cube.vert.spv") (Join-Path $root "cube.vert")
if ($LASTEXITCODE -ne 0) { throw "glslangValidator failed for cube.vert" }
& $glslang -V -o (Join-Path $temp "cube.frag.spv") (Join-Path $root "cube.frag")
if ($LASTEXITCODE -ne 0) { throw "glslangValidator failed for cube.frag" }

$builder = New-Object System.Text.StringBuilder
[void]$builder.AppendLine("// Generated by gen_shaders.ps1 - do not edit.")
[void]$builder.AppendLine("#pragma once")
[void]$builder.AppendLine("#include <cstdint>")
[void]$builder.AppendLine("")

function Add-ByteArray([string]$name, [string]$path) {
    $bytes = [System.IO.File]::ReadAllBytes($path)
    [void]$builder.AppendLine("static const unsigned char $name" + "[] = {")
    for ($i = 0; $i -lt $bytes.Length; $i += 12) {
        $end = [Math]::Min($i + 11, $bytes.Length - 1)
        $line = ($bytes[$i..$end] | ForEach-Object { "0x{0:X2}" -f $_ }) -join ", "
        [void]$builder.AppendLine("    $line,")
    }
    [void]$builder.AppendLine("};")
    [void]$builder.AppendLine("static const unsigned int ${name}Size = $($bytes.Length);")
    [void]$builder.AppendLine("")
}

function Add-SpvArray([string]$name, [string]$path) {
    $bytes = [System.IO.File]::ReadAllBytes($path)
    if ($bytes.Length % 4 -ne 0) { throw "$path is not a multiple of 4 bytes" }
    [void]$builder.AppendLine("static const std::uint32_t $name" + "[] = {")
    for ($i = 0; $i -lt $bytes.Length; $i += 16) {
        $end = [Math]::Min($i + 15, $bytes.Length - 1)
        $values = @()
        for ($j = $i; $j -le $end; $j += 4) {
            $value = [BitConverter]::ToUInt32($bytes, $j)
            $values += ("0x{0:X8}" -f $value)
        }
        [void]$builder.AppendLine("    " + ($values -join ", ") + ",")
    }
    [void]$builder.AppendLine("};")
    [void]$builder.AppendLine("static const unsigned int ${name}Size = $($bytes.Length);")
    [void]$builder.AppendLine("")
}

Add-ByteArray "kCubeVs5" (Join-Path $temp "cube_vs5.cso")
Add-ByteArray "kCubePs5" (Join-Path $temp "cube_ps5.cso")
Add-ByteArray "kCubeVs4" (Join-Path $temp "cube_vs4.cso")
Add-ByteArray "kCubePs4" (Join-Path $temp "cube_ps4.cso")
Add-SpvArray "kCubeVertSpv" (Join-Path $temp "cube.vert.spv")
Add-SpvArray "kCubeFragSpv" (Join-Path $temp "cube.frag.spv")

Set-Content -Path (Join-Path $root "shaders_generated.h") -Value $builder.ToString() -Encoding ASCII
Write-Host "wrote shaders_generated.h"
